# -*- coding: utf-8 -*-
"""Message service for the orchestrator.

Provides helpers to persist user/assistant messages and tool audit messages.
All functions operate on a provided SQLAlchemy ``Session`` and never commit;
the caller (API layer) is responsible for transaction boundaries.
"""

from __future__ import annotations

from typing import Any, List, Optional

from sqlalchemy.orm import Session

from ...models import Message, Conversation

# Valid role literals as defined in the Message ORM model



def _ensure_conversation_exists(session: Session, conversation_id: int) -> Conversation:
    """Retrieve the Conversation or raise if not found.

    The service layer never exposes internal IDs in errors; we raise a generic
    ``ValueError`` which the API can translate to a 404 response.
    """
    conv = session.get(Conversation, conversation_id)
    if conv is None:
        raise ValueError("Conversation not found")
    return conv


def add_message(
    session: Session,
    conversation_id: int,
    turn_id: int,
    content: str,
    role: str,
) -> Message:
    """Persist a regular (customer or assistant) message.

    * ``role`` must be either ``"customer"`` or ``"assistant"`` â€“ the ``tool``
      role is reserved for ``add_tool_message``.
    * The function validates the conversation exists, adds the new Message,
      flushes to obtain the autogenerated primary key, and returns the instance.
    """
    if role not in {"customer", "assistant"}:
        raise ValueError(f"Invalid role '{role}'. Expected 'customer' or 'assistant'.")
    # Ensure the conversation exists first
    _ensure_conversation_exists(session, conversation_id)

    msg = Message(
        conversation_id=conversation_id,
        turn_id=turn_id,
        role=role,
        content=content,
        # toolâ€‘audit columns stay NULL (default)
    )
    session.add(msg)
    session.flush()
    return msg


def add_tool_message(
    session: Session,
    conversation_id: int,
    turn_id: int,
    content: str,
    tool_name: Optional[str] = None,
    tool_call_id: Optional[str] = None,
    tool_arguments: Optional[Any] = None,
    tool_status: Optional[str] = None,
    tool_result: Optional[Any] = None,
    tool_error: Optional[str] = None,
) -> Message:
    """Persist a message that carries toolâ€‘audit information.

    The ``role`` is forced to ``"tool"``. All toolâ€‘related columns map directly to
    the ORM fields; JSONâ€‘compatible values (dict / list / primitive) may be
    stored in ``tool_arguments`` and ``tool_result``.
    """
    # Ensure conversation exists
    _ensure_conversation_exists(session, conversation_id)

    msg = Message(
        conversation_id=conversation_id,
        turn_id=turn_id,
        role="tool",
        content=content,
        tool_name=tool_name,
        tool_call_id=tool_call_id,
        tool_arguments=tool_arguments,
        tool_status=tool_status,
        tool_result=tool_result,
        tool_error=tool_error,
    )
    session.add(msg)
    session.flush()
    return msg


def get_conversation_messages(session: Session, conversation_id: int) -> List[Message]:
    """Return all messages for a conversation ordered by ``turn_id``.

    Raises ValueError("Conversation not found") if the conversation does not exist.
    Ordering by ``turn_id`` (as used by the application) provides deterministic chronological order.
    """
    # Verify conversation exists for a clearer error path
    _ensure_conversation_exists(session, conversation_id)
    return (
        session.query(Message)
        .filter(Message.conversation_id == conversation_id)
        .order_by(Message.turn_id, Message.message_id)
        .all()
    )
